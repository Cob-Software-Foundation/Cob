#!/bin/sh
# gen_stdlib_static.sh -- generates the two headers a COB_STDLIB_STATIC build
# (the browser/WASM interpreter, or `make cob_interp_static`) compiles in:
#
#   stdlib_static.h  declarations + a { name, function } table of every
#                    exported function of the modules that are linked in
#   stdlib_embed.h   the .cob wrapper source of EVERY module, so `shuck porch`
#                    works with no files on disk
#
# usage: sh tools/gen_stdlib_static.sh <outdir> "<linked modules>" "<wrapper modules>"
set -e
out=$1; linked=$2; wrappers=$3
mkdir -p "$out"

{
    echo "/* generated by tools/gen_stdlib_static.sh -- do not edit */"
    for m in $linked; do
        grep -ho 'COB_EXPORT CobValue [A-Za-z0-9_]*' "stdlib/$m.c" |
            awk '{ print "COB_EXPORT CobValue " $3 "(CobValue *argv, int argc);" }'
    done
    echo "static const struct { const char *name; CobFFIFunc fn; } cob_static_table[] = {"
    for m in $linked; do
        grep -ho 'COB_EXPORT CobValue [A-Za-z0-9_]*' "stdlib/$m.c" |
            awk '{ print "    { \"" $3 "\", " $3 " }," }'
    done
    echo "};"
} > "$out/stdlib_static.h"

{
    echo "/* generated by tools/gen_stdlib_static.sh -- do not edit */"
    echo "static const struct { const char *name; const char *source; } cob_embedded_wrappers[] = {"
    for m in $wrappers; do
        echo "    { \"$m\","
        awk '{ gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); print "      \"" $0 "\\n\"" }' "stdlib/$m.cob"
        echo "    },"
    done
    echo "};"
} > "$out/stdlib_embed.h"
